import { it, expect } from "vitest";
import { existsSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";
import { createServer } from "vite";
import { chromium } from "playwright-core";
const executable = process.env.BFF_TEST_BROWSER ?? "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
it.skipIf(!existsSync(executable))("beUI preserves form contracts, Chinese tab identity and nested overlay focus", async () => {
  const server = await createServer({ configFile: resolve("apps/desktop/vite.config.ts"), server: { host: "127.0.0.1", port: 0, strictPort: false, fs: { allow: [resolve(".")] } } });
  await server.listen();
  const browser = await chromium.launch({ executablePath: executable, headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 820, height: 760 }, reducedMotion: "reduce" });
    const errors: string[] = []; page.on("pageerror", (error) => errors.push(error.message));
    await page.goto(`http://127.0.0.1:${(server.httpServer!.address() as { port: number }).port}/@fs/${resolve("tests/fixtures/beui-interface.html")}`);
    const number = page.getByLabel("数量", { exact: true });
    await number.fill("9");
    expect(await number.evaluate((el) => (el as HTMLInputElement).validity.rangeOverflow)).toBe(true);
    await number.fill("3");
    await page.getByLabel("口令", { exact: true }).fill("fixture-only");
    await page.getByLabel("日期", { exact: true }).fill("2026-11-04");
    await page.getByRole("button", { name: "保存", exact: true }).click();
    expect(await page.getByLabel("保存结果").textContent()).toBe("");
    const select = page.getByRole("combobox", { name: "选项", exact: true });
    expect(await select.getAttribute("aria-invalid")).toBe("true");
    await select.press("ArrowDown");
    await page.getByRole("option", { name: "默认值", exact: true }).waitFor();
    await page.keyboard.press("ArrowDown");
    expect(await page.getByRole("option", { name: "第一项", exact: true }).evaluate((el) => el === document.activeElement)).toBe(true);
    await page.keyboard.press("Enter");
    expect(await select.innerText()).toContain("第一项");
    const field = page.getByLabel("口令", { exact: true });
    const beforeFocus = await field.boundingBox();
    await field.focus();
    expect(await field.evaluate(el => ({ outline: getComputedStyle(el).outlineStyle, fieldShadow: getComputedStyle(el.parentElement!).boxShadow }))).toMatchObject({ outline: "none" });
    expect(await field.evaluate(el => getComputedStyle(el.parentElement!).boxShadow)).toContain("1px");
    expect(await field.boundingBox()).toEqual(beforeFocus);
    const checkbox = page.getByRole("checkbox", { name: "保存后启用", exact: true });
    await page.getByText("保存后启用", { exact: true }).click();
    expect(await checkbox.getAttribute("aria-checked")).toBe("true");
    await checkbox.press("Space");
    expect(await checkbox.getAttribute("aria-checked")).toBe("false");
    await page.getByRole("button", { name: "保存", exact: true }).click();
    expect(JSON.parse((await page.getByLabel("保存结果").textContent())!)).toEqual({ number: 3, password: "fixture-only", date: "2026-11-04", choice: "one", checked: false, realEvent: true });
    await select.click(); await page.getByRole("option", { name: "默认值", exact: true }).click();
    expect(await select.innerText()).toContain("默认值");
    const ids = await page.getByRole("tab").evaluateAll((tabs) => tabs.map((tab) => tab.id));
    expect(new Set(ids).size).toBe(3);
    await page.getByRole("tab", { name: "概览", exact: true }).press("ArrowRight");
    expect(await page.getByRole("tabpanel", { name: "设定", exact: true }).textContent()).toBe("设定内容");
    for (const tab of await page.getByRole("tab").all()) expect(await tab.evaluate((el) => document.getElementById(el.getAttribute("aria-controls")!)?.getAttribute("aria-labelledby") === el.id)).toBe(true);
    const opener = page.getByRole("button", { name: "打开抽屉", exact: true }); await opener.click();
    const drawer = page.getByRole("dialog", { name: "控件抽屉", exact: true }); await drawer.waitFor();
    expect(await page.evaluate(() => document.body.style.overflow)).toBe("hidden");
    const nested = drawer.getByRole("combobox", { name: "选项", exact: true });
    await nested.click(); await page.getByRole("option", { name: "第二项", exact: true }).waitFor();
    const option = (await page.getByRole("option", { name: "第二项", exact: true }).boundingBox())!;
    expect(option.x).toBeGreaterThanOrEqual((await drawer.boundingBox())!.x);
    expect(option.x + option.width).toBeLessThanOrEqual(820);
    expect(option.y + option.height).toBeLessThanOrEqual(760);
    mkdirSync("build/beui-interface", { recursive: true });
    await page.screenshot({ path: "build/beui-interface/drawer-select-820.png" });
    await page.keyboard.press("Escape");
    expect(await nested.getAttribute("aria-expanded")).toBe("false");
    expect(await drawer.isVisible()).toBe(true);
    expect(await nested.evaluate((el) => el === document.activeElement)).toBe(true);
    await drawer.getByRole("button", { name: "声音选项", exact: true }).click();
    const voice = drawer.getByLabel("声音", { exact: true }); await voice.fill("voice-fixture");
    expect(await voice.evaluate((el) => el === document.activeElement)).toBe(true);
    await page.screenshot({ path: "build/beui-interface/drawer-popover-820.png" });
    await page.keyboard.press("Escape"); expect(await drawer.isVisible()).toBe(true);
    await page.keyboard.press("Escape"); await drawer.waitFor({ state: "detached" });
    expect(await opener.evaluate((el) => el === document.activeElement)).toBe(true);
    expect(await page.evaluate(() => document.body.style.overflow)).toBe("");
    expect(errors).toEqual([]);
  } finally { await browser.close(); await server.close(); }
}, 30000);

it.skipIf(!existsSync(executable))("product drawers and disclosures remain usable without animation frames", async () => {
  const server = await createServer({ configFile: resolve("apps/desktop/vite.config.ts"), server: { host: "127.0.0.1", port: 0, strictPort: false, fs: { allow: [resolve(".")] } } });
  await server.listen();
  const browser = await chromium.launch({ executablePath: executable, headless: true });
  try {
    for (const reducedMotion of ["no-preference", "reduce"] as const) for (const frozen of [false, true]) {
      const page = await browser.newPage({ viewport: { width: 900, height: 680 }, reducedMotion });
      page.setDefaultTimeout(4000);
      const errors: string[] = []; page.on("pageerror", (error) => errors.push(error.message));
      // Install before Motion imports/captures rAF; changing it after load is insufficient.
      await page.addInitScript(() => {
        const nativeRaf = window.requestAnimationFrame.bind(window);
        const state = { frozen: false };
        Object.assign(window, { __fixtureFrames: state });
        window.requestAnimationFrame = (callback) => state.frozen ? 0 : nativeRaf((time) => { if (!state.frozen) callback(time); });
      });
      await page.goto(`http://127.0.0.1:${(server.httpServer!.address() as { port: number }).port}/@fs/${resolve("tests/fixtures/beui-interface.html")}`);
      const opener = page.getByRole("button", { name: "打开抽屉", exact: true });
      await opener.waitFor();
      await page.evaluate((value) => { (window as unknown as { __fixtureFrames: { frozen: boolean } }).__fixtureFrames.frozen = value; }, frozen);
      await opener.click();
      const drawer = page.getByRole("dialog", { name: "控件抽屉", exact: true });
      await drawer.waitFor();
      const bounds = (await drawer.boundingBox())!;
      expect(bounds.x).toBeGreaterThanOrEqual(0);
      expect(bounds.x + bounds.width).toBeLessThanOrEqual(900);
      expect(await drawer.evaluate((el) => ({ opacity: getComputedStyle(el).opacity, transform: getComputedStyle(el).transform, focused: el.contains(document.activeElement) }))).toEqual({ opacity: "1", transform: "none", focused: true });
      expect(await page.evaluate(() => document.body.style.overflow)).toBe("hidden");
      const trigger = drawer.getByRole("button", { name: "隐藏字段", exact: true });
      const content = drawer.locator('[data-slot="collapsible-content"]');
      expect((await trigger.boundingBox())!.height).toBe(40);
      await trigger.click();
      expect(await trigger.getAttribute("aria-expanded")).toBe("true");
      expect((await content.boundingBox())!.height).toBeGreaterThan(40);
      expect(await content.evaluate((el) => ({ inert: (el as HTMLElement).inert, opacity: getComputedStyle(el.firstElementChild!).opacity }))).toEqual({ inert: false, opacity: "1" });
      expect(await trigger.locator('[data-slot="collapsible-indicator"]').evaluate((el) => getComputedStyle(el).transform)).toBe("matrix(-1, 0, 0, -1, 0, 0)");
      const input = drawer.getByLabel("折叠输入", { exact: true });
      await input.fill("保留草稿");
      // Close without moving focus first, to exercise the content's return-focus contract.
      await trigger.evaluate((el) => (el as HTMLButtonElement).click());
      expect(await content.evaluate((el) => ({ inert: (el as HTMLElement).inert, height: el.getBoundingClientRect().height }))).toEqual({ inert: true, height: 0 });
      expect(await trigger.evaluate((el) => el === document.activeElement)).toBe(true);
      await page.keyboard.press("Tab");
      await trigger.focus();
      expect(await trigger.evaluate((el) => el.matches(":focus-visible"))).toBe(true);
      expect(await trigger.evaluate((el) => getComputedStyle(el).outlineColor)).toBe("rgb(34, 120, 159)");
      await trigger.click();
      expect(await input.inputValue()).toBe("保留草稿");
      await trigger.locator("span").first().evaluate((el) => { el.textContent = "这是一条需要自然换行的很长很长的折叠标题".repeat(4); });
      expect((await drawer.locator('[data-slot="collapsible-trigger"]').boundingBox())!.height).toBeGreaterThan(40);
      await drawer.getByRole("button", { name: "声音选项", exact: true }).focus();
      await page.keyboard.press("Tab");
      const close = drawer.getByRole("button", { name: "关闭", exact: true });
      expect(await close.evaluate((el) => el === document.activeElement)).toBe(true);
      // The icon's keyboard tooltip owns the first Escape; the drawer owns the next.
      expect(await close.getAttribute("aria-describedby")).not.toBeNull();
      await page.keyboard.press("Escape");
      expect(await close.getAttribute("aria-describedby")).toBeNull();
      expect(await drawer.isVisible()).toBe(true);
      await page.keyboard.press("Escape");
      await drawer.waitFor({ state: "detached" });
      expect(await opener.evaluate((el) => el === document.activeElement)).toBe(true);
      expect(await page.evaluate(() => document.body.style.overflow)).toBe("");
      await opener.click();
      await page.getByRole("button", { name: "关闭抽屉", exact: true }).dispatchEvent("click");
      await drawer.waitFor({ state: "detached" });
      expect(await opener.evaluate((el) => el === document.activeElement)).toBe(true);
      expect(errors).toEqual([]);
      await page.close();
    }
  } finally { await browser.close(); await server.close(); }
}, 30000);
