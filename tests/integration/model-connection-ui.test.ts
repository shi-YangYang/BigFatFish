import { it, expect } from 'vitest';
import { existsSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { createServer } from 'vite';
import { chromium } from 'playwright-core';
const executable = process.env.BFF_TEST_BROWSER ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
it.skipIf(!existsSync(executable))('model form tests current drafts, fetches/selects models, saves effort and ignores stale responses', async () => {
  const server = await createServer({ configFile: resolve('apps/desktop/vite.config.ts'), server: { host: '127.0.0.1', port: 0, strictPort: false, fs: { allow: [resolve('.')] } } }); await server.listen();
  const browser = await chromium.launch({ executablePath: executable, headless: true });
  let release = () => {};
  try {
    const page = await browser.newPage({ viewport: { width: 1100, height: 900 }, reducedMotion: 'reduce' });
    page.setDefaultTimeout(4000);
    let hold = false, rejectTest = false, saved: Record<string, unknown>[] = [];
    const requests: { route: string; body: Record<string, unknown> }[] = [];
    const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
    await page.route('**/api/v1/**', async route => {
      const name = new URL(route.request().url()).pathname, body = route.request().postDataJSON() ?? {}; requests.push({ route: name, body });
      if (hold && (name.endsWith('/test') || name.endsWith('/discover'))) await new Promise<void>(resolve => { release = resolve; });
      if (name.endsWith('/test')) return route.fulfill({ status: rejectTest ? 409 : 200, json: rejectTest ? { error: 'MODEL_AUTH_FAILED' } : { ok: true, elapsedMs: 123 } });
      if (name.endsWith('/discover')) return route.fulfill({ json: { models: [{ id: 'fixture-one', name: '测试模型' }, { id: 'fixture-two', name: 'fixture-two' }], elapsedMs: 20 } });
      if (name.endsWith('/models') && route.request().method() === 'POST') { saved = [{ ...body, apiKey: undefined, hasKey: true }]; return route.fulfill({ json: saved[0] }); }
      return route.fulfill({ json: name.endsWith('/models') ? saved : {} });
    });
    await page.goto(`http://127.0.0.1:${(server.httpServer!.address() as { port: number }).port}/@fs/${resolve('tests/fixtures/model-connection.html')}`);
    expect(await page.getByLabel('服务地址', { exact: true }).count()).toBe(0);
    await page.getByRole('button', { name: '新建配置', exact: true }).click();
    await page.getByLabel('服务地址', { exact: true }).fill('https://example.invalid/v1');
    await page.getByLabel('API Key', { exact: true }).fill('fixture-only-key');
    await page.getByRole('button', { name: '收起', exact: true }).click();
    await page.getByRole('button', { name: '继续编辑', exact: true }).click();
    expect(await page.getByLabel('API Key', { exact: true }).inputValue()).toBe('fixture-only-key');
    await page.getByRole('button', { name: '获取模型列表', exact: true }).click();
    await page.getByText('获取到 2 个模型', { exact: true }).waitFor();
    expect(requests.find(request => request.route.endsWith('/discover'))?.body.model).toBe(''); expect(saved).toHaveLength(0);
    await page.getByRole('combobox', { name: '可用模型', exact: true }).click();
    await page.getByRole('option', { name: '测试模型（fixture-one）', exact: true }).click();
    expect(await page.getByLabel('模型名称', { exact: true }).inputValue()).toBe('fixture-one');
    await page.getByRole('combobox', { name: '推理强度', exact: true }).click(); await page.getByRole('option', { name: '最高', exact: true }).click();
    await page.getByRole('button', { name: '测试连接', exact: true }).click(); await page.getByText('连接成功，模型已响应 · 123 毫秒', { exact: true }).waitFor();
    expect(requests.find(req => req.route.endsWith('/test'))?.body).toMatchObject({ reasoningEffort: 'max', model: 'fixture-one', apiKey: 'fixture-only-key' });
    expect(saved).toHaveLength(0);
    mkdirSync('build/model-connection', { recursive: true });
    await page.screenshot({ path: 'build/model-connection/models-1100.png' });
    await page.getByRole('combobox', { name: '推理强度', exact: true }).click(); await page.screenshot({ path: 'build/model-connection/effort-1100.png' }); await page.keyboard.press('Escape');
    await page.getByLabel('模型名称', { exact: true }).fill('manual-model');
    expect(await page.getByText(/连接成功/).count()).toBe(0);
    await page.getByRole('button', { name: '保存模型', exact: true }).click(); await page.getByText('配置已保存', { exact: true }).waitFor();
    expect(saved[0]).toMatchObject({ model: 'manual-model', reasoningEffort: 'max' });
    expect(await page.getByLabel('API Key', { exact: true }).count()).toBe(0);
    expect(await page.getByRole('heading', { name: '默认用途' }).count()).toBe(1);
    await page.locator('.model-name').first().click();
    expect(await page.getByLabel('API Key', { exact: true }).inputValue()).toBe('');
    expect(await page.getByRole('combobox', { name: '推理强度', exact: true }).innerText()).toContain('最高');
    rejectTest = true; await page.getByRole('button', { name: '测试连接', exact: true }).click(); await page.getByRole('alert').filter({ hasText: '鉴权失败' }).waitFor();
    rejectTest = false; hold = true;
    await page.getByRole('button', { name: '测试连接', exact: true }).click(); await page.getByRole('button', { name: '正在测试…', exact: true }).waitFor();
    await page.getByLabel('模型名称', { exact: true }).fill('changed-model'); release(); await page.waitForTimeout(100);
    expect(await page.getByText(/连接成功/).count()).toBe(0);
    await page.getByRole('button', { name: '获取模型列表', exact: true }).click(); await page.getByRole('button', { name: '正在获取…', exact: true }).waitFor();
    await page.getByLabel('服务地址', { exact: true }).fill('https://other.invalid/v1'); release(); hold = false; await page.waitForTimeout(100);
    expect(await page.getByRole('combobox', { name: '可用模型', exact: true }).count()).toBe(0);
    await page.getByRole('combobox', { name: '提供商', exact: true }).click(); await page.getByRole('option', { name: 'DeepSeek', exact: true }).click();
    expect(await page.getByRole('combobox', { name: '推理强度', exact: true }).innerText()).toBe('默认');
    await page.setViewportSize({ width: 380, height: 760 }); await page.getByRole('combobox', { name: '推理强度', exact: true }).click();
    expect(await page.getByRole('option').allTextContents()).toEqual(['默认', '关闭', '低', '高', '最高']);
    await page.screenshot({ path: 'build/model-connection/effort-380.png' }); await page.keyboard.press('Escape');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth && document.querySelector('.workspace-main')!.scrollWidth <= document.querySelector('.workspace-main')!.clientWidth)).toBe(true);
    await page.getByRole('button', { name: '测试连接', exact: true }).scrollIntoViewIfNeeded(); await page.screenshot({ path: 'build/model-connection/models-380.png' });
    expect(errors).toEqual([]);
  } finally { release(); await browser.close(); await server.close(); }
}, 30000);
